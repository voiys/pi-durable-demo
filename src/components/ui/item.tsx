import * as React from "react"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"
import { Slot } from "radix-ui"

import { Separator } from "@/components/ui/separator"

/** A list of rows: a real <ul>, so each row is an <li> (`<Item asChild><li>`, or an <li> around an interactive Item). */
function ItemGroup({ className, ...props }: React.ComponentProps<"ul">) {
  return (
    <ul
      data-slot="item-group"
      className={cn("group/item-group flex flex-col", className)}
      {...props}
    />
  )
}

function ItemSeparator({
  className,
  ...props
}: React.ComponentProps<typeof Separator>) {
  return (
    <Separator
      data-slot="item-separator"
      orientation="horizontal"
      className={cn("my-0", className)}
      {...props}
    />
  )
}

// DESIGN.md §5/§6: rows are flat (no borders, space separates them); a clickable row (a, button) takes the accent hover
// fill. `card` is a lifted surface on the canvas (Things two-tone): surface fill, the composer hairline, 12px radius.
// Focus is drawn inside the row, since rows run flush to the edge of scrolling lists that would clip an outer ring.
const itemVariants = cva(
  "group/item flex flex-wrap items-center rounded-md text-left text-sm transition-colors duration-150 focus-visible:outline-2 focus-visible:-outline-offset-2 [a,button]:w-full [a,button]:hover:bg-accent",
  {
    variants: {
      variant: {
        default: "bg-transparent",
        card: "rounded-lg border border-transparent bg-surface shadow-composer",
      },
      size: {
        default: "gap-3 p-3",
        sm: "min-h-8 gap-2 px-2 py-1.5",
      },
    },
    defaultVariants: {
      variant: "default",
      size: "default",
    },
  }
)

function Item({
  className,
  variant = "default",
  size = "default",
  asChild = false,
  ...props
}: React.ComponentProps<"div"> &
  VariantProps<typeof itemVariants> & { asChild?: boolean }) {
  const Comp = asChild ? Slot.Root : "div"
  return (
    <Comp
      data-slot="item"
      data-variant={variant}
      data-size={size}
      className={cn(itemVariants({ variant, size, className }))}
      {...props}
    />
  )
}

const itemMediaVariants = cva(
  "flex shrink-0 items-center justify-center gap-2 group-has-[[data-slot=item-description]]/item:translate-y-0.5 group-has-[[data-slot=item-description]]/item:self-start [&_svg]:pointer-events-none",
  {
    variants: {
      variant: {
        default: "bg-transparent",
      },
    },
    defaultVariants: {
      variant: "default",
    },
  }
)

function ItemMedia({
  className,
  variant = "default",
  ...props
}: React.ComponentProps<"div"> & VariantProps<typeof itemMediaVariants>) {
  return (
    <div
      data-slot="item-media"
      data-variant={variant}
      className={cn(itemMediaVariants({ variant, className }))}
      {...props}
    />
  )
}

